export const frozenDatasets = {
  country_month: countryMonth.map(([country, costMtd, revMtd, advMtd, leadsMtd, costEom, revEom, advEom, leadsEom]) => ({
    month: MONTH,
    month_to: MONTH,
    is_ytd: false,
    country,
    data_through: DATA_THROUGH,
    days_elapsed: DAYS_ELAPSED,
    days_in_month: DAYS_IN_MONTH,
    traveller_cost_mtd: costMtd,
    rental_revenue_mtd: revMtd,
    advertiser_cost_mtd: advMtd,
    leads_mtd: leadsMtd,
    traveller_cost_eom: costEom,
    rental_revenue_eom: revEom,
    advertiser_cost_eom: advEom,
    leads_eom: leadsEom,
  })),

  targets: targetRows.map(([country, rental, cost, net, advCost, leads]) => ({
    month: MONTH,
    country,
    rental_revenue: rental,
    traveller_cost: cost,
    net_revenue: net,
    advertiser_cost: advCost,
    advertiser_leads: leads,
  })),

  channel_split: splitRows.flatMap(([country, shares]) =>
    SPLIT_CHANNELS.map((channel, i) => ({ country, channel, share: shares[i] })),
  ),

  channel_month: channelMonth.map(([country, channel, mtd, eom, avg7]) => ({
    month: MONTH,
    days_elapsed: DAYS_ELAPSED,
    days_in_month: DAYS_IN_MONTH,
    country,
    channel,
    traveller_cost_mtd: mtd,
    traveller_cost_eom: eom,
    avg_daily_7d: avg7,
  })),

  channel_daily: channelDaily.flatMap(([country, channel, csv]) =>
    series(csv).map((cost, i) => ({
      month: MONTH,
      country,
      channel,
      day: addDays(CHANNEL_SERIES_START, i),
      cost,
    })),
  ),

  daily_pace: dailyPace.flatMap(([country, costCsv, revCsv, lyCostCsv, lyRevCsv]) => {
    const cost = series(costCsv);
    const revenue = series(revCsv);
    const lyCost = series(lyCostCsv);
    const lyRevenue = series(lyRevCsv);
    const lyCostTotal = round2(lyCost.reduce((s, v) => s + v, 0));
    const lyRevenueTotal = round2(lyRevenue.reduce((s, v) => s + v, 0));
    let costCum = 0;
    let revCum = 0;
    let lyCostCum = 0;
    let lyRevCum = 0;

    return Array.from({ length: DAYS_IN_MONTH }, (_, i) => {
      const hasData = i < cost.length;
      if (hasData) {
        costCum += cost[i];
        revCum += revenue[i];
      }
      lyCostCum += lyCost[i];
      lyRevCum += lyRevenue[i];

      return {
        month: MONTH,
        day: addDays(MONTH + '-01', i),
        day_of_month: i + 1,
        days_in_month: DAYS_IN_MONTH,
        country,
        cost: hasData ? cost[i] : null,
        revenue: hasData ? revenue[i] : null,
        cost_cum: hasData ? round2(costCum) : null,
        revenue_cum: hasData ? round2(revCum) : null,
        ly_cost_cum: round2(lyCostCum),
        ly_revenue_cum: round2(lyRevCum),
        ly_cost_total: lyCostTotal,
        ly_revenue_total: lyRevenueTotal,
      };
    });
  }),
};

